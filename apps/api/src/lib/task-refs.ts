// Свои номера задачи (SPEC §8.6).
//
// То, чем задачу зовут ВНЕ Chatick: экраны в макете, пункты договора, позиции
// сметы. Поле намеренно свободное: у каждой команды свой счёт, и навязывать им
// формат — значит сделать поле бесполезным для всех, кроме одной.
//
// Разбираем ТОЛЬКО по запятой. «12 - 14» — один номер, а не два: у одних это
// диапазон экранов, у других составной шифр, и решать за них нельзя. Пробелы
// по краям срезаем, внутри оставляем как написали.

/** Цифры, точки, дефисы и пробелы внутри; запятая — разделитель. */
const ALLOWED = /[^0-9.\-\s,]/g

export const MAX_REFS_LENGTH = 200

/** Строка → отдельные номера. Пустые куски («1,,2» и хвостовая запятая) выпадают. */
export function parseRefs(value: string): string[] {
  return value
    .replace(ALLOWED, '')
    .split(',')
    .map((x) => x.trim())
    .filter(Boolean)
}

/**
 * Привести к виду, в котором храним: номера через запятую с пробелом.
 *
 * Нормализуем на записи, а не на чтении: иначе «1,2» и «1, 2» — две разные
 * строки в базе, и поиск по номеру находил бы то одну, то другую.
 */
export function normalizeRefs(value: string): string {
  return parseRefs(value).join(', ').slice(0, MAX_REFS_LENGTH)
}
