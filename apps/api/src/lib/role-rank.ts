// Внешняя система повышает, но не понижает (SPEC §8.42).
//
// Состав команды ведёт внешняя система — кто работает в компании, знает она.
// А кем человек будет у НАС — админом компании, руководителем проекта — она не
// знает и знать не может: этих понятий в ней нет. Роль по умолчанию у неё
// одна, «участник», и она приходит в каждом пуше.
//
// Прежде каждый пуш перезаписывал роль присланной. Человека делали админом
// в Chatick, Atlas подключал очередной проект — и админ молча становился
// участником. Не «иногда»: при каждой синхронизации, и на уровне компании, и
// на уровне проекта.
//
// Поэтому пуш поднимает роль, но не опускает. Повышение из внешней системы
// проходит: если там человека сделали руководителем, это осмысленный сигнал.
// Понижение — только руками у нас, где такое решение вообще можно принять
// осознанно.
//
// Ошибку внешней системе при этом не возвращаем. Для неё вызов удался: состав
// она задала, и он такой, как она просила. Роль — не её зона, и падать из-за
// чужой зоны ответственности её скрипт не должен.

/** Чем больше число, тем больше прав. */
const COMPANY_RANK: Record<string, number> = { member: 0, manager: 1, admin: 2 }
const PROJECT_RANK: Record<string, number> = { member: 0, admin: 1, owner: 2 }

/**
 * Роль, которую ставим по итогу пуша: большая из текущей и присланной.
 *
 * `current` — null, если человека в компании/проекте ещё нет: тогда спорить не
 * о чем, ставим присланную.
 */
function keepHigher(rank: Record<string, number>, current: string | null, incoming: string): string {
  if (!current) return incoming
  return (rank[current] ?? 0) > (rank[incoming] ?? 0) ? current : incoming
}

export const keepHigherCompanyRole = (current: string | null, incoming: string) =>
  keepHigher(COMPANY_RANK, current, incoming)

export const keepHigherProjectRole = (current: string | null, incoming: string) =>
  keepHigher(PROJECT_RANK, current, incoming)
