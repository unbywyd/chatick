import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

/**
 * Панель «Мои задачи»: группировка по проектам.
 *
 * Раньше задачи текущего проекта подсвечивались зелёным. На деле подсвеченной
 * оказывалась половина списка — а метка на большинстве перестаёт что-либо
 * значить и превращается в фон, вызывающий вопрос «почему эти другие».
 *
 * Имя проекта теперь в заголовке секции, а не в каждой строке: строки короче,
 * границы между чужими работами видны сами собой.
 */

const panel = readFileSync(
  join(import.meta.dirname, '../../../app/src/components/chat/MyTasksPanel.tsx'),
  'utf8',
)

describe('раскладка списка', () => {
  it('подсветки текущего проекта больше нет', () => {
    /**
     * Метка на половине списка — это не метка, а полосатый фон.
     *
     * Проверяем не конкретные классы, а сам приём: карточка задачи красится
     * одинаково всегда. Ищи мы точную строку — её хватило бы переписать
     * иначе, и подсветка вернулась бы при зелёном тесте (проверено саботажем).
     */
    const rowFn = panel.match(/const row = \(task: MyTask[\s\S]*?\n  \}/)?.[0] ?? ''
    expect(rowFn, 'строка задачи не найдена').not.toBe('')
    expect(rowFn, 'класс карточки снова зависит от условия').toMatch(
      /className="w-full rounded-lg border bg-card p-2\.5 text-start transition-colors hover:bg-accent"/,
    )
    expect(rowFn, 'в строке снова сравнивают проект ради вида').not.toMatch(/=== projectId/)
  })

  it('по проектам — умолчание', () => {
    // Пусто в хранилище читаем как «да»: человек, который ничего не выбирал,
    // должен увидеть тот вид, ради которого всё и делалось.
    expect(panel).toMatch(/localStorage\.getItem\(GROUP_KEY\) !== '0'/)
  })

  it('выбор раскладки переживает перезагрузку', () => {
    // Это привычка человека, а не свойство проекта — держим в браузере.
    expect(panel).toMatch(/localStorage\.setItem\(GROUP_KEY/)
  })

  it('имя проекта не дублируется в строке', () => {
    /**
     * В группировке оно уже в заголовке секции. Показывать его ещё и в каждой
     * строке значит вернуть ровно ту длину, от которой уходили.
     */
    expect(panel).toMatch(/const row = \(task: MyTask, withProject: boolean\)/)
    expect(panel, 'строки в секциях снова с именем проекта').toMatch(/g\.tasks\.map\(\(task\) => row\(task, false\)\)/)
    expect(panel, 'сквозной список потерял имя проекта').toMatch(/items\.map\(\(task\) => row\(task, true\)\)/)
  })
})

describe('секции', () => {
  it('сворачиваются', () => {
    expect(panel).toMatch(/const \[closed, setClosed\] = useState<Set<string>>/)
    expect(panel, 'содержимое секции не скрывается').toMatch(/\{!shut && <ul/)
  })

  it('открыты по умолчанию', () => {
    // Пустое множество закрытых: свернуть — осознанное действие человека.
    expect(panel).toMatch(/useState<Set<string>>\(new Set\(\)\)/)
  })

  it('текущий проект идёт первым', () => {
    /**
     * Первым, а не прокруткой к нему: панель отвечает на вопрос «что горит», и
     * уехав к текущему проекту, она спрятала бы просроченное из соседнего —
     * ровно то, ради чего её открывают.
     */
    expect(panel).toMatch(/a\.id === projectId \? -1 : b\.id === projectId \? 1 : 0/)
  })

  it('заголовок секции липкий', () => {
    // В длинном списке иначе не понять, чей проект сейчас перед тобой.
    expect(panel).toMatch(/sticky top-0/)
  })
})

describe('порядок задач', () => {
  it('внутри секции — от новых к старым', () => {
    /**
     * Когда проект выбран, разговор о его работе, и первым хочется видеть
     * свежее. Сквозной список при этом остаётся по срочности — там вопрос
     * другой.
     */
    expect(panel).toMatch(/\+new Date\(b\.createdAt\) - \+new Date\(a\.createdAt\)/)
  })

  it('сквозной список идёт как отдал сервер', () => {
    // Сервер сортирует: сначала просроченные, потом от старых к новым.
    // Пересортировав здесь, мы потеряли бы срочность.
    const flat = panel.match(/<ul className="space-y-1">\{items\.map[\s\S]{0,120}/)?.[0] ?? ''
    expect(flat, 'сквозной список не найден').not.toBe('')
    expect(flat, 'сквозной список пересортирован на клиенте').not.toMatch(/\.sort\(/)
  })
})
