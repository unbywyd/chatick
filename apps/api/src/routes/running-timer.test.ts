import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

/**
 * Идущий таймер на стартовом экране компании.
 *
 * Остановить его можно было, только зайдя в проект: на телефоне это несколько
 * касаний, а часы капают всё время, пока человек ищет нужный экран.
 */

const app = (p: string) =>
  readFileSync(join(import.meta.dirname, '../../../app/src/', p), 'utf8').replace(/\r\n/g, '\n')
const timer = app('components/company/MyRunningTimer.tsx')
const start = app('screens/StartScreen.tsx')

describe('таймер виден и останавливается в одно касание', () => {
  it('берёт свои таймеры по сессии, без проектного токена', () => {
    // На странице компании проектного токена нет вовсе — проектная ручка
    // /api/v1/time/running там просто не ответит.
    //
    // Саботаж: заменить на проектную ручку — тест падает.
    expect(timer, 'используется не сессионная ручка').toContain("api<{ items: Running[] }>('/api/v1/my/time/running')")
  })

  it('останавливает той же правкой, что кнопка в проекте', () => {
    // endedAt = сейчас. Отдельной ручки «стоп» заводить не нужно: PATCH по
    // сессии уже умеет это и правит только СВОИ записи.
    //
    // Саботаж: убрать endedAt — тест падает.
    expect(timer, 'остановка не проставляет конец').toContain('endedAt: new Date().toISOString()')
    expect(timer, 'правка идёт не по сессионной ручке').toContain('`/api/v1/my/time/${id}`')
  })

  it('после остановки обновляются все списки этих же часов', () => {
    // Иначе строка исчезает из одного места и висит в двух других.
    for (const key of ['my-time-running', 'my-time-recent', 'company-time']) {
      expect(timer, `не обновляется ${key}`).toContain(`queryKey: ['${key}']`)
    }
  })

  it('счётчик тикает сам, а не ждёт запроса', () => {
    // Перезапрос идёт раз в минуту — без локального тика «живой» таймер
    // выглядел бы остановившимся.
    //
    // Саботаж: убрать setInterval — тест падает.
    expect(timer, 'счётчик не обновляется между запросами').toMatch(/setInterval\(\(\) => tick/)
  })

  it('когда таймера нет — не рисуем ничего', () => {
    // Полоса «ничего не запущено» отвечала бы на вопрос, которого никто не
    // задавал, и отодвигала вниз то, ради чего заходят.
    //
    // Саботаж: убрать ранний возврат — тест падает.
    expect(timer, 'пустой блок всё равно рисуется').toContain('if (!items.length) return null')
  })

  it('длинное имя проекта не выдавливает кнопку «стоп»', () => {
    // Ради кнопки блок и существует: она обязана оставаться на экране.
    expect(timer, 'блок не переносится').toContain('flex min-w-0 flex-wrap items-center')
    expect(timer, 'имя проекта не обрезается').toContain('min-w-0 flex-1 truncate')
  })

  it('показан на стартовом экране выше вкладок', () => {
    // Забытый таймер важен независимо от того, какую вкладку человек открыл.
    //
    // Саботаж: убрать компонент — тест падает.
    const at = start.indexOf('<MyRunningTimer />')
    expect(at, 'таймер не подключён').toBeGreaterThan(-1)
    expect(at, 'таймер ниже вкладок').toBeLessThan(start.indexOf('{tab === '))
  })
})
