import { describe, it, expect } from 'vitest'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

/**
 * Идущий таймер на стартовом экране компании.
 *
 * Остановить его можно было, только зайдя в проект: на телефоне это несколько
 * касаний, а часы капают всё время, пока человек ищет нужный экран.
 */

const app = (p: string) =>
  readFileSync(join(import.meta.dirname, '../../../app/src/', p), 'utf8').replace(/\r\n/g, '\n')
const timer = app('components/company/MyRunningTimer.tsx')
const start = app('screens/StartScreen.tsx')

describe('таймер запускается с главной', () => {
  const time = readFileSync(join(import.meta.dirname, 'time.ts'), 'utf8').replace(/\r\n/g, '\n')

  it('правила запуска не продублированы', () => {
    // Лимит параллельных таймеров и проверка членства — это правила.
    // Выписанные дважды, они однажды разойдутся, и с главной станет можно
    // то, чего нельзя из проекта.
    //
    // Саботаж: скопировать тело во вторую ручку — тест падает.
    expect(time, 'общей функции запуска нет').toContain('async function startTimer(')
    const starts = (time.match(/const cfg = await timeConfigForProject/g) ?? []).length
    expect(starts, 'логика запуска продублирована').toBe(1)
  })

  it('сессионная ручка требует проект явно', () => {
    // Проектного токена на главной нет вовсе: без projectId в теле часы
    // записывать некуда.
    //
    // Саботаж: сделать projectId необязательным — тест падает.
    const at = time.indexOf("timeMineRoute.post(")
    expect(at, 'сессионной ручки запуска нет').toBeGreaterThan(-1)
    expect(time.slice(at, at + 420), 'проект не обязателен').toContain('projectId: z.string(),')
    expect(time, 'пустой проект не отсекается').toContain("if (!projectId) return c.json({ error: 'projectId is required' }, 400)")
  })

  it('клиент предлагает последний проект одним нажатием', () => {
    // Почти всегда продолжают то, чем занимались: ради этого случая не
    // должно быть выбора из трёх десятков проектов.
    //
    // Саботаж: убрать быструю кнопку — тест падает.
    expect(timer, 'нет запуска с главной').toContain("api('/api/v1/my/time/start'")
    expect(timer, 'первый проект не вынесен кнопкой').toContain('const first = projects[0]!')
  })

  it('список проектов не грузится, когда таймер идёт', () => {
    // Кнопки запуска в этот момент и не видно — запрос был бы впустую.
    expect(timer, 'список грузится всегда').toContain('enabled: !running.data?.items.length')
  })
})
describe('таймер виден и останавливается в одно касание', () => {
  it('берёт свои таймеры по сессии, без проектного токена', () => {
    // На странице компании проектного токена нет вовсе — проектная ручка
    // /api/v1/time/running там просто не ответит.
    //
    // Саботаж: заменить на проектную ручку — тест падает.
    expect(timer, 'используется не сессионная ручка').toContain("api<{ items: Running[] }>('/api/v1/my/time/running')")
  })

  it('останавливает той же правкой, что кнопка в проекте', () => {
    // endedAt = сейчас. Отдельной ручки «стоп» заводить не нужно: PATCH по
    // сессии уже умеет это и правит только СВОИ записи.
    //
    // Саботаж: убрать endedAt — тест падает.
    expect(timer, 'остановка не проставляет конец').toContain('endedAt: new Date().toISOString()')
    expect(timer, 'правка идёт не по сессионной ручке').toContain('`/api/v1/my/time/${id}`')
  })

  it('после остановки обновляются все списки этих же часов', () => {
    // Иначе строка исчезает из одного места и висит в двух других.
    for (const key of ['my-time-running', 'my-time-recent', 'company-time']) {
      expect(timer, `не обновляется ${key}`).toContain(`queryKey: ['${key}']`)
    }
  })

  it('счётчик тикает сам, а не ждёт запроса', () => {
    // Перезапрос идёт раз в минуту — без локального тика «живой» таймер
    // выглядел бы остановившимся.
    //
    // Саботаж: убрать setInterval — тест падает.
    expect(timer, 'счётчик не обновляется между запросами').toMatch(/setInterval\(\(\) => tick/)
  })

  it('без таймера предлагаем запуск, а не пустоту', () => {
    // Раньше блок просто исчезал. Теперь на его месте кнопка «запустить»:
    // останавливать с главной уже умели, а запускать приходилось идти в
    // проект — несимметрично.
    //
    // Но если запускать нечего (человек ни разу не вёл часы) — ничего не
    // рисуем: кнопка без проектов ведёт в никуда.
    //
    // Саботаж: убрать ранний возврат при пустом списке — тест падает.
    expect(timer, 'пустой блок всё равно рисуется').toContain('if (!projects.length) return null')
  })

  it('длинное имя проекта не выдавливает кнопку «стоп»', () => {
    // Ради кнопки блок и существует: она обязана оставаться на экране.
    expect(timer, 'блок не переносится').toContain('flex min-w-0 flex-wrap items-center')
    expect(timer, 'имя проекта не обрезается').toContain('min-w-0 flex-1 truncate')
  })

  it('показан на стартовом экране выше вкладок', () => {
    // Забытый таймер важен независимо от того, какую вкладку человек открыл.
    //
    // Саботаж: убрать компонент — тест падает.
    const at = start.indexOf('<MyRunningTimer />')
    expect(at, 'таймер не подключён').toBeGreaterThan(-1)
    expect(at, 'таймер ниже вкладок').toBeLessThan(start.indexOf('{tab === '))
  })
})

describe('таймер не перекрыт липкими панелями', () => {
  const timeTab = app('components/company/CompanyTimeTab.tsx')
  const hook = app('hooks/useStickyHeight.ts')

  it('у таймера своя липкая полоса, а не место между двумя чужими', () => {
    // Он стоял обычным блоком между вкладками (sticky top-0 z-20) и
    // фильтрами часов (sticky -top-8 z-10). Обе панели непрозрачны и
    // наезжали на него с двух сторон: на вкладке «Часы» от строки с
    // таймером была видна только середина — обрезаны и кнопка «стоп», и
    // счётчик.
    //
    // Саботаж: убрать sticky у обёртки — тест падает.
    const at = start.indexOf('<MyRunningTimer />')
    const wrap = start.slice(Math.max(0, at - 700), at)
    expect(wrap, 'обёртка таймера не липкая').toContain('sticky')
    expect(wrap, 'таймер не встаёт под вкладки').toContain('var(--tabs-h')
  })

  it('таймер выше фильтров, но ниже вкладок', () => {
    // Порядок задаёт, кто кого перекрывает при прокрутке. Вкладки сверху —
    // это главная навигация; фильтры уходят под таймер, а не на него.
    const at = start.indexOf('<MyRunningTimer />')
    const wrap = start.slice(Math.max(0, at - 700), at)
    expect(wrap, 'таймер не над фильтрами').toContain('z-[15]')
    expect(start, 'вкладки не выше таймера').toContain('sticky top-0 z-20')
    expect(timeTab, 'фильтры не ниже таймера').toContain('z-10')
  })

  it('высота вкладок меряется, а не зашита числом', () => {
    // На широком экране вкладки в один ряд (69px), на телефоне переносятся
    // в два (105px). Любое число оказалось бы неверным на одной из ширин.
    //
    // Саботаж: заменить var(--tabs-h) на константу — тест падает.
    expect(start, 'высота вкладок не публикуется').toContain('useStickyHeight(')
    expect(hook, 'высота не пересчитывается при переносе рядов').toContain('ResizeObserver')
  })

  it('фильтры часов встают под вкладки, а не выше края окна', () => {
    // Было -top-8: панель парковалась на 32px ВЫШЕ окна, и её фон закрывал
    // всё, что оказалось в этой полосе, — в том числе таймер.
    //
    // Саботаж: вернуть -top-8 — тест падает.
    expect(timeTab, 'фильтры паркуются выше края окна').not.toContain('sticky -top-8')
    expect(timeTab, 'фильтры не считают отступ от вкладок').toContain('var(--tabs-h')
  })

  it('высота пишется на общего предка, а не на сам элемент', () => {
    // Вкладки и таймер — СОСЕДИ вкладки «Часы» по дереву, а не её предки.
    // Переменная, поставленная на сам элемент, наследуется только вниз, в его
    // потомков, — фильтры её просто не увидели бы и вернулись под вкладки.
    //
    // Саботаж: писать в el.style вместо предка — тест падает.
    // Ищем сам поиск предка, а не упоминание: слово есть и в комментарии.
    expect(hook, 'высота пишется на сам элемент').toMatch(/closest\(\s*'\[data-sticky-root\]'\s*\)/)
    expect(hook, 'переменная ставится не на найденного предка').toMatch(/host\s*as\s*HTMLElement\)?\.style\.setProperty/)
    expect(start, 'корень для переменных не размечен').toContain('<div data-sticky-root')
  })

  it('фильтры встают под таймер, а не делят с ним полосу', () => {
    // Оба липнут под вкладками. Без слагаемого таймера фильтры парковались бы
    // на той же высоте и уезжали под него (z-10 против z-[15]), пока он идёт.
    //
    // Саботаж: убрать --timer-h из calc — тест падает.
    expect(timeTab, 'фильтры не учитывают высоту таймера').toContain('var(--timer-h')
    expect(start, 'таймер не публикует свою высоту').toContain('useStickyHeight("--timer-h")')
  })

  it('без таймера полосы под вкладками не остаётся', () => {
    // Обёртка есть всегда, а таймер рисует null. Пустая липкая полоса с
    // непрозрачным фоном висела бы под вкладками без причины.
    //
    // Саботаж: убрать скрытие пустой обёртки — тест падает.
    const at = start.indexOf('<MyRunningTimer />')
    const wrap = start.slice(Math.max(0, at - 700), at)
    expect(wrap, 'пустая обёртка видна').toContain(':has(section)')
  })
})
