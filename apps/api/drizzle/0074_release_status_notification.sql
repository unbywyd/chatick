-- Уведомление о смене стадии версии.
--
-- Автор версии её завёл и хочет знать, что с ней стало: «залил в TestFlight»,
-- «прошли ревью» — это ответ на вопрос, который он иначе задаёт голосом.
-- Исполнители связанных задач — по тому же правилу «только затронутым»: они
-- делают работу, ради которой версия и существует.
--
-- Тому, кто сам двигает стадию, уведомление не уходит: notify() исключает
-- актора из получателей, и отдельной проверки для этого не нужно.
ALTER TYPE "notification_event" ADD VALUE IF NOT EXISTS 'release_status';
