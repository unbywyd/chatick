-- Имя сборки: какое именно приложение выкачено.
--
-- У проекта бывает несколько приложений — клиент и провайдер, — и тип сборки
-- их не различает: обе версии под iOS имеют buildType='ios'. Сводка «что
-- сейчас в проде» ключевалась только по типу, и второе приложение затиралось
-- первым: из четырёх версий было видно две.
--
-- Колонка необязательная: у заведённых раньше версий имени нет, и NOT NULL
-- сломал бы их. Обязательность живёт в форме и в ручках создания.
ALTER TABLE "releases" ADD COLUMN IF NOT EXISTS "app_name" text;

-- Сводка теперь группирует по приложению И типу сборки.
DROP INDEX IF EXISTS "releases_project_type_idx";
CREATE INDEX IF NOT EXISTS "releases_project_app_type_idx"
  ON "releases" ("project_id", "app_name", "build_type");
