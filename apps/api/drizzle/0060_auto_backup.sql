-- Автоматический бэкап компании (SPEC §8.48).
--
-- Бэкап существовал только как кнопка: нажал — получил архив. Раз в сутки его
-- никто не нажимает, а вспоминают о нём в тот день, когда данные уже потеряны.
--
-- Пишется в хранилище компании (своё S3/R2) — на нашей инфраструктуре копия
-- смысла не имеет: она погибнет вместе с оригиналом.
ALTER TABLE "companies" ADD COLUMN IF NOT EXISTS "auto_backup" boolean DEFAULT false NOT NULL;

-- Когда прошёл последний удачный бэкап и чем закончился последний вообще.
-- Молча сломавшийся бэкап хуже отсутствующего: на него рассчитывают.
ALTER TABLE "companies" ADD COLUMN IF NOT EXISTS "last_backup_at" timestamp with time zone;
ALTER TABLE "companies" ADD COLUMN IF NOT EXISTS "last_backup_error" text;
-- Письмо о сбое шлём один раз, а не каждые сутки: ежедневная жалоба на одну и
-- ту же поломку читается как спам и перестаёт работать.
ALTER TABLE "companies" ADD COLUMN IF NOT EXISTS "backup_error_notified_at" timestamp with time zone;

-- Отдельный бакет под бэкапы — необязательный, пусто означает «в основной».
--
-- Держать архивы там же, куда пишутся рабочие вложения, — смешивать две разные
-- задачи: у бэкапа своя ротация и свой срок хранения, а токен к нему можно
-- выдать более узкий. Ключи те же, что у основного хранилища: это тот же
-- аккаунт, отличается только бакет.
ALTER TABLE "company_storage" ADD COLUMN IF NOT EXISTS "backup_bucket" text;
