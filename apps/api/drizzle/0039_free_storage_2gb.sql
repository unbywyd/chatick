-- Бесплатный пул хранилища: 5 ГБ → 2 ГБ (SPEC §7).
--
-- Меняем и значение по умолчанию, и уже созданные компании: иначе старые
-- продолжали бы жить на прежнем лимите, и «бесплатно 2 ГБ» было бы неправдой
-- для половины базы.
--
-- Тех, кто уже занял больше нового лимита, не трогаем: отнимать место задним
-- числом нельзя — загрузка просто перестанет добавлять новое, пока не почистят.

ALTER TABLE companies ALTER COLUMN storage_limit SET DEFAULT '2147483648';

UPDATE companies
SET storage_limit = '2147483648'
WHERE storage_limit = '5368709120';
