-- Объявление компании: то, что не привязано ни к задаче, ни к проекту.
--
-- «Завтра отдыхаем», «изменили политику отпусков», «сервер переезжает в
-- субботу» — сообщения, ради которых сейчас идут в мессенджер, а через
-- неделю никто не помнит, кому написали и дошло ли.
--
-- Все прежние события выросли из чего-то: задачи, заметки, таймера. Отсюда и
-- NOT NULL на project_id — уведомления просто не бывало без повода внутри
-- проекта. Объявление — первый случай, когда повод вне проектов вовсе.
--
-- ALTER TYPE ... ADD VALUE не работает внутри транзакции — отдельным
-- стейтментом, как в 0079 и 0088.
ALTER TYPE "notification_event" ADD VALUE IF NOT EXISTS 'announcement';

-- Проект перестаёт быть обязательным.
--
-- Только для объявлений: у остальных событий он есть и будет — «вам назначили
-- задачу» без задачи бессмысленно. Но одна колонка на все события, и запретить
-- пустоту выборочно нельзя.
ALTER TABLE "notifications" ALTER COLUMN "project_id" DROP NOT NULL;

-- Компания у уведомления — чтобы объявление знало, чьё оно.
--
-- Раньше её выводили из проекта: notifications → projects → companies. Без
-- проекта выводить неоткуда, а знать надо: инбокс группирует по компаниям, и
-- объявление без неё повисло бы в воздухе.
ALTER TABLE "notifications" ADD COLUMN IF NOT EXISTS "company_id" text
  REFERENCES "companies"("id") ON DELETE CASCADE;

-- Заполняем компанию у существующих: у них есть проект, и она берётся из него.
-- Без этого старые уведомления выпали бы из выборок по компании — молча.
UPDATE "notifications" n
SET "company_id" = p."company_id"
FROM "projects" p
WHERE p."id" = n."project_id" AND n."company_id" IS NULL;

-- Инбокс отбирает по человеку и непрочитанности; компания добавляется к этому
-- при показе объявлений.
CREATE INDEX IF NOT EXISTS "notifications_company_idx" ON "notifications" ("company_id", "created_at" DESC);
