-- Учёт времени переезжает с проекта на компанию (SPEC §8.36).
--
-- Часовой пояс, рабочие часы и правила забытого таймера — свойства
-- организации, а не отдельной работы. Задавать их заново в каждом проекте
-- значило заводить десять способов разойтись: у одного проекта неделя с
-- понедельника, у соседнего с воскресенья, и «эта неделя» в отчётах у них
-- разная.
--
-- projects.time_config НЕ удаляем. Во-первых, там лежат уже настроенные
-- значения — из них и наполняется компания ниже. Во-вторых, оно остаётся
-- точкой переопределения: из интерфейса настройки убраны, но если однажды
-- понадобится проект в другом поясе, включать будет что.
ALTER TABLE "companies" ADD COLUMN IF NOT EXISTS "time_config" text DEFAULT '{}' NOT NULL;

-- Срок сдачи проекта. Дата, а не отметка времени: «до 14-го» — это до конца
-- дня, и час здесь только мешал бы. NULL — срока нет, и это обычное дело.
ALTER TABLE "projects" ADD COLUMN IF NOT EXISTS "deadline" timestamp with time zone;

-- Переносим настройки самого раннего настроенного проекта в его компанию.
--
-- Настроенным считаем тот, у кого поле не пустое и не '{}': пустой объект
-- стоит у всех проектов с рождения и настройкой не является. Если в компании
-- настроенных проектов несколько, берём самый старый — он заводился первым, и
-- пояс в нём выставляли осознанно, а не копированием.
--
-- Компании, где настраивать было нечего, остаются с '{}' и читаются как
-- значения по умолчанию.
UPDATE "companies" c
SET "time_config" = src."time_config"
FROM (
  SELECT DISTINCT ON (p."company_id")
         p."company_id", p."time_config"
  FROM "projects" p
  WHERE p."time_config" IS NOT NULL
    AND btrim(p."time_config") <> ''
    AND btrim(p."time_config") <> '{}'
  ORDER BY p."company_id", p."created_at"
) src
WHERE c."id" = src."company_id"
  AND btrim(c."time_config") IN ('', '{}');
