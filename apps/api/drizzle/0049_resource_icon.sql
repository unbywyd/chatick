-- Иконка ресурса и необязательное имя (SPEC §8.1).
--
-- Ресурс — это почти всегда ссылка: логин к панели, макет, репозиторий.
-- Имя ему придумывают редко, поэтому обязательным оно быть не должно —
-- подставим домен. Пустым ресурс при этом остаться не может: пусто и в
-- ссылке, и в имени — это не ресурс.
ALTER TABLE "credentials" ALTER COLUMN "name" SET DEFAULT '';

-- Картинка сайта (og:image или favicon) как data-URI: в списке ссылку
-- узнают по значку быстрее, чем по строке текста. Килобайты — держать
-- ради них отдельный файл в хранилище несоразмерно.
ALTER TABLE "credentials" ADD COLUMN IF NOT EXISTS "icon" text;
