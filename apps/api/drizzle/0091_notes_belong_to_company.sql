-- Заметки принадлежат КОМПАНИИ, проект — необязательная метка.
--
-- Природа изменилась. Заметки задумывались как журнал наблюдений ассистента:
-- «люди сказали противоречащее», «реализация разошлась с макетом». Отсюда и
-- типы contradiction / mismatch / gap — они про то, что заметил ассистент в
-- разговоре, и вне проекта бессмысленны.
--
-- Стало нужно другое: база знаний команды. «Cardcom отклоняет иностранные
-- карты, лечится так» — знание про Cardcom, а не про проект, где на него
-- наткнулись. Привязав такое к WashMe, мы его прячем: в Vpure столкнутся с
-- тем же и не найдут.
--
-- Поэтому владелец теперь компания, а проект — метка ПРОИСХОЖДЕНИЯ, а не
-- граница доступа: «это выяснилось там». Она помогает вернуться к контексту и
-- сузить поиск, но не закрывает запись от остальных.
--
-- Права на уровне заметок убраны отдельным решением: доступ даёт членство в
-- компании. Из 104 участников проектов домен notes не ограничил ни один — он
-- существовал, но им никогда не пользовались.

-- 1. Компанию заполняем из проекта, пока связь ещё обязательна. Без этого
--    существующие записи остались бы без владельца и пропали бы из всех
--    списков — тихо, потому что запрос по company_id их просто не вернёт.
UPDATE "notes" n
SET "company_id" = p."company_id"
FROM "projects" p
WHERE p."id" = n."project_id" AND n."company_id" IS NULL;

-- 2. Теперь компания обязательна, а проект — нет.
--    Порядок важен: сделать company_id NOT NULL до шага 1 нельзя.
ALTER TABLE "notes" ALTER COLUMN "company_id" SET NOT NULL;
ALTER TABLE "notes" ALTER COLUMN "project_id" DROP NOT NULL;

-- 3. Удаление проекта больше не уносит заметки.
--
--    Было ON DELETE CASCADE: закрыли проект — исчезло всё, что в нём поняли.
--    Ровно наоборот тому, ради чего база знаний заводится: решение переживает
--    проект, в котором найдено. Теперь связь просто обнуляется, запись
--    остаётся у компании.
ALTER TABLE "notes" DROP CONSTRAINT IF EXISTS "notes_project_id_projects_id_fk";
ALTER TABLE "notes" ADD CONSTRAINT "notes_project_id_projects_id_fk"
  FOREIGN KEY ("project_id") REFERENCES "projects"("id") ON DELETE SET NULL;

-- 4. Типы журнала наблюдений переводим в типы базы знаний.
--
--    contradiction («люди спорят»), mismatch («код разошёлся с макетом»),
--    gap («в спеке не описано») — свидетельства о моменте, а не знание.
--    reminder перестаёт быть типом: напомнить можно о чём угодно, для этого
--    есть remind_at.
--
--    В базе таких записей нет ни одной — перевод на будущее, чтобы старые
--    значения не остались висеть, если где-то всплывут.
UPDATE "notes" SET "type" = 'attention' WHERE "type" IN ('contradiction', 'mismatch', 'gap');
UPDATE "notes" SET "type" = 'note' WHERE "type" = 'reminder';

-- 5. Поиск теперь всегда идёт по компании — индекс под это.
--    Прежний notes_company_idx включал scope, которого больше нет в отборе.
DROP INDEX IF EXISTS "notes_company_idx";
CREATE INDEX IF NOT EXISTS "notes_company_idx" ON "notes" ("company_id", "created_at" DESC);
-- Проект остаётся фильтром «покажи, что писали здесь» — не границей.
CREATE INDEX IF NOT EXISTS "notes_project_idx2" ON "notes" ("project_id") WHERE "project_id" IS NOT NULL;
