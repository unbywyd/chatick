-- Поиск по смыслу: векторы текстов.
--
-- Обычный поиск ищет слова, а человек спрашивает смысл. «Не приходит смс» и
-- «SMS с кодом не доставляется» — один вопрос и ни одного общего слова, кроме
-- аббревиатуры. Для иврита это не удобство, а единственный путь: словаря
-- иврита в Postgres нет вовсе (есть арабский, идиш — иврита нет), и
-- полнотекстовый поиск дал бы ему только точное совпадение слова, без форм.
-- Проверено: «בדיקה» и «לבדוק» — одно понятие, а триграммы дают им 0.00.
--
-- ОБЩАЯ таблица, не «векторы заметок». Ассистент ищет не заметку и не задачу,
-- а ОТВЕТ: он может лежать в описании задачи, в комментарии, в заметке.
-- Три отдельных поиска заставили бы звать три инструмента и склеивать самому.
-- Поэтому здесь entity_type + entity_id, и подключение задач — это строка в
-- коде, а не вторая таблица.
--
-- 512 чисел, а не 1536. text-embedding-3-small умеет отдавать урезанный
-- вектор, и замер на живом запросе показал: качество то же (разрыв −0.049
-- против −0.048), а места втрое меньше. На 256 уже заметно хуже.
--
-- halfvec (половинная точность) взяли бы охотнее, но он появился в pgvector
-- 0.7, а на сервере 0.6.0.
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE IF NOT EXISTS "embeddings" (
  "id" text PRIMARY KEY,
  -- note | task | task_comment | document — что именно проиндексировано
  "entity_type" text NOT NULL,
  "entity_id" text NOT NULL,
  -- Проект и компания ДУБЛИРУЮТСЯ сюда намеренно: поиск обязан отсеивать
  -- чужое по правам, и делать это в самом запросе, а не после. Джойн на
  -- четыре таблицы ради одного фильтра стоил бы дороже дублирования.
  "project_id" text REFERENCES "projects"("id") ON DELETE CASCADE,
  "company_id" text REFERENCES "companies"("id") ON DELETE CASCADE,
  "embedding" vector(512),
  -- Отпечаток текста, с которого считан вектор. Правка, не менявшая текст
  -- (перестановка тегов, смена статуса), не должна тратить деньги на пересчёт.
  "content_hash" text NOT NULL,
  -- Модель: сменив её, все векторы придётся считать заново — они несравнимы
  -- между моделями. Поле говорит, какие именно устарели.
  "model" text NOT NULL DEFAULT 'text-embedding-3-small',
  "created_at" timestamptz NOT NULL DEFAULT now(),
  "updated_at" timestamptz NOT NULL DEFAULT now()
);

-- Одна запись на сущность. Уникальность в базе, а не в коде: индексация идёт
-- фоном, и два тика планировщика могут взяться за одну заметку одновременно.
CREATE UNIQUE INDEX IF NOT EXISTS "embeddings_entity_idx" ON "embeddings" ("entity_type", "entity_id");

-- Поиск всегда идёт в пределах компании: искать по чужим данным нельзя, и
-- фильтр стоит первым в запросе.
CREATE INDEX IF NOT EXISTS "embeddings_company_idx" ON "embeddings" ("company_id");

-- Индекс близости. HNSW, а не IVFFlat: он не требует обучения на готовых
-- данных, а у нас база наполняется постепенно — IVFFlat пришлось бы
-- перестраивать по мере роста.
--
-- vector_cosine_ops: векторы нормализованы, и косинус здесь то же, что
-- скалярное произведение. Считаем им — так принято у этой модели.
CREATE INDEX IF NOT EXISTS "embeddings_vec_idx" ON "embeddings"
  USING hnsw ("embedding" vector_cosine_ops);

-- Очередь пересчёта.
--
-- Вектор считается ВНЕ запроса пользователя: обращение к модели занимает
-- сотни миллисекунд, а сохранение заметки должно быть мгновенным. И если
-- модель недоступна, заметка обязана сохраниться всё равно.
--
-- Без очереди такая запись потерялась бы молча: она есть, а поиском не
-- находится, и узнать об этом можно только не найдя её однажды.
CREATE TABLE IF NOT EXISTS "embedding_queue" (
  "id" text PRIMARY KEY,
  "entity_type" text NOT NULL,
  "entity_id" text NOT NULL,
  "project_id" text REFERENCES "projects"("id") ON DELETE CASCADE,
  -- Сколько раз пробовали. Модель может отвечать отказом (нет денег, лимит),
  -- и вечно долбиться в неё не надо — после нескольких попыток отступаем.
  "attempts" integer NOT NULL DEFAULT 0,
  "last_error" text,
  "created_at" timestamptz NOT NULL DEFAULT now()
);

-- Одна и та же сущность в очереди один раз: правя заметку пять раз подряд,
-- человек не должен создавать пять заданий на пересчёт.
CREATE UNIQUE INDEX IF NOT EXISTS "embedding_queue_entity_idx" ON "embedding_queue" ("entity_type", "entity_id");
-- Разбор очереди: сначала то, что не падало.
CREATE INDEX IF NOT EXISTS "embedding_queue_pick_idx" ON "embedding_queue" ("attempts", "created_at");
