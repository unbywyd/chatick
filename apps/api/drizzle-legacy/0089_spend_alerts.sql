-- Отметки об отправленных предупреждениях о тратах.
--
-- Планировщик тикает каждые пять минут. Без отметки письмо «траты за месяц
-- перевалили за порог» ушло бы 288 раз в сутки — и человек отключил бы его
-- на второй день, вместе с настоящими предупреждениями.
--
-- Отдельная таблица, а не колонка у компании: порог считается по ВСЕМ
-- тратам сервера, а не по одной компании. Вешать глобальную отметку на
-- произвольную строку в companies значило бы врать о том, к чему она
-- относится.
--
-- Ключ — период («2026-08») плюс вид предупреждения. Один и тот же порог в
-- следующем месяце сработает снова: это и есть смысл месячного лимита.
--
-- Не в файле на диске: приложение переезжает между машинами, а отметка,
-- потерянная при переезде, превращается в повторное письмо. И не в памяти:
-- перезапуск случается чаще, чем месяц.
CREATE TABLE IF NOT EXISTS "spend_alerts" (
  "id" text PRIMARY KEY,
  -- «2026-08» — месяц, за который считались траты
  "period" text NOT NULL,
  -- вид предупреждения: monthly_threshold. Заведён на будущее: порогов
  -- может стать больше одного, и тогда они не столкнутся ключами.
  "kind" text NOT NULL DEFAULT 'monthly_threshold',
  -- сколько было потрачено на момент отправки — видно в письме и в истории
  "amount_usd" text NOT NULL,
  "sent_to" text NOT NULL,
  "created_at" timestamptz NOT NULL DEFAULT now()
);

-- Один и тот же период с одним видом — только раз. Уникальность в базе, а не
-- в коде: два процесса приложения тикают независимо, и проверка «сначала
-- посмотрели, потом вставили» пропустила бы второе письмо между этими шагами.
CREATE UNIQUE INDEX IF NOT EXISTS "spend_alerts_period_idx" ON "spend_alerts" ("period", "kind");
