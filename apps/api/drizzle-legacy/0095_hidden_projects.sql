-- Скрытые проекты: «убрал со стола до завтра».
--
-- Просьба дословно: «в конце дня я убираю стол, и в списке остаются только
-- проекты, где есть открытые задачи». Буквально так делать нельзя — у
-- половины команды задач на себе нет вовсе, а проекты нужны: там переписка,
-- ревью, сборки. У Хадиль 14 проектов и задачи в трёх, у Таля 13 и в двух:
-- одиннадцать исчезли бы, хотя работа в них идёт.
--
-- Поэтому решает ЧЕЛОВЕК, а не правило. Как в мессенджерах: скрыл — лежит,
-- пришло уведомление — вернулось само.
--
-- Поле в project_members, а НЕ в projects: это личное состояние. Я убрал у
-- себя — у остальных проект на месте. В projects уже есть archived_at, но он
-- про другое: там ПМ убирает законченный проект у ВСЕЙ компании. Два разных
-- понятия, и в интерфейсе они названы по-разному — «Архив» и «Скрытые».
ALTER TABLE "project_members" ADD COLUMN IF NOT EXISTS "hidden_at" timestamptz;

-- Отбор всегда идёт по одному человеку: «мои проекты, кроме скрытых».
CREATE INDEX IF NOT EXISTS "project_members_hidden_idx"
  ON "project_members" ("user_id", "hidden_at");
