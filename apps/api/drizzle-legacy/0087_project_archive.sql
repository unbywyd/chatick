-- Архив проектов: законченный проект убирается с глаз, но остаётся целым.
--
-- Отдельная колонка, а не deleted_at: архив обратим и ничего не трогает —
-- задачи, переписка, файлы и часы на месте. Удаление необратимо. Свести их в
-- одну колонку значит однажды стереть то, что просили просто убрать из списка.
--
-- Nullable без умолчания: NULL читается как «живой проект», и существующие
-- двадцать два проекта StartPlan остаются в списках ровно там, где были.
--
-- IF NOT EXISTS: миграции здесь накатываются вручную через psql, повторный
-- прогон падать не должен.
ALTER TABLE "projects" ADD COLUMN IF NOT EXISTS "archived_at" timestamptz;

-- Индекс частичный: в запросах нас интересуют ЖИВЫЕ проекты, и их
-- подавляющее большинство. Полный индекс по nullable-колонке хранил бы записи
-- обо всех, тогда как читаем мы всегда одну сторону условия.
CREATE INDEX IF NOT EXISTS "projects_active_idx" ON "projects" ("company_id") WHERE "archived_at" IS NULL;
