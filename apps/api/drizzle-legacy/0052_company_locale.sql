-- Язык компании и проекта (SPEC §8.39).
--
-- Язык письма брался из личных настроек получателя, а у приглашения — из
-- настроек приглашающего. У человека, которого ещё нет в системе, настроек
-- нет вовсе: израильская компания заводит сотрудника и шлёт ему письмо
-- по-английски.
--
-- Компания знает свой язык. Проект наследует его, но может отличаться:
-- команда на одном проекте может говорить не на языке всей фирмы.
ALTER TABLE "companies" ADD COLUMN IF NOT EXISTS "locale" text NOT NULL DEFAULT 'en';

-- NULL = наследовать от компании. Отдельное значение от 'en' по умолчанию:
-- иначе нельзя отличить «явно выбрали английский» от «не выбирали».
ALTER TABLE "projects" ADD COLUMN IF NOT EXISTS "locale" text;
