-- Ответ под пунктом чек-листа — событие, а не тишина.
--
-- Чек-лист здесь — способ спросить: «каким ключом подписывать?» пишет один, а
-- знает ответ обычно другой. Ответ приходил, и не всплывал НИГДЕ: ни в
-- инбоксе, ни в комментариях, ни в самой задаче. Человек, ответивший на десять
-- пунктов, вынужден был отдельно писать комментарий «я ответил в пунктах» —
-- иначе никто бы не заметил. Когда человек дублирует уведомление руками,
-- механизма нет.
--
-- В коде это допущение записано прямо (routes/tasks.ts, у checklistAccess):
-- «Отдельных уведомлений нет: человек и так смотрит на свою задачу». Верно,
-- пока задачу ведёт человек. Задачу, заведённую ассистентом, никто не
-- «смотрит»: ответ ложится в пункт и остаётся там навсегда.
--
-- Отдельное событие, а не task_comment. Три довода:
--
--  1. Инбокс группирует по event. Слепив ответы с комментариями, мы не смогли
--     бы отделить «на мой вопрос ответили» от «кто-то что-то написал» иначе
--     как разбором текста ссылки — то есть догадками.
--
--  2. Заголовок «X прокомментировал(а) TASK-81» — неправда. Человек откроет
--     комментарии и ничего там не найдёт.
--
--  3. task_comment есть в NOTIFY_EVENTS: проект, выключивший комментарии,
--     молча перестал бы получать и ответы на свои вопросы. Это разные вещи, и
--     выключавший одно не соглашался терять второе.
--
-- В NOTIFY_EVENTS новое событие НЕ кладём — там список переключателей в
-- настройках. Выключить единственный сигнал о том, что на твой вопрос
-- ответили, незачем; note_reminder и timer_running отсутствуют там по той же
-- причине.
--
-- ALTER TYPE ... ADD VALUE не работает внутри транзакции — отдельным
-- стейтментом, как в 0079.
ALTER TYPE "notification_event" ADD VALUE IF NOT EXISTS 'checklist_answer';
