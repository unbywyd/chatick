-- Различаем «выбрал английский» и «язык не выбирал» (SPEC §8.44).
--
-- users.locale — NOT NULL DEFAULT 'en', поэтому у человека, заведённого через
-- API компании, там оказывается 'en' — не потому что он так решил, а потому
-- что колонка не пустая.
--
-- Письма это принимали за осознанный выбор и уходили по-английски, минуя язык
-- компании. Израильская фирма заводит сотрудников через свою систему, у неё
-- locale = he, а люди получают английские письма.
--
-- Отдельный признак, а не NULL в самой колонке: locale читают в полутора
-- десятках мест, и допускать там пустое значение — значит чинить каждое.
ALTER TABLE "users" ADD COLUMN IF NOT EXISTS "locale_set_by_user" boolean DEFAULT false NOT NULL;

-- Никого не помечаем выбравшим: записи в users.locale в коде нет вовсе —
-- сменить язык через API нельзя, у всех стоит дефолтный 'en'. Пометить их
-- «выбравшими» значило бы навсегда закрепить английский за людьми, которые
-- ничего не выбирали.
--
-- Когда появится настройка личного языка, она будет ставить этот признак.
