-- Структурные предложения в sandbox (SPEC §5.5.3).
--
-- Раньше ИИ мог предложить ровно одно: другой текст того же сообщения. Всё
-- остальное — «это похоже на задачу для Артёма» — он умел сказать только
-- словами, и человеку приходилось идти заводить её руками.
--
-- kind описывает, ЧТО предложено (пусто — исторический вариант текста),
-- payload держит поля для исполнения. Исполняет сервер по кнопке: если бы
-- создавала модель «когда человек согласился», создалось бы то, как она поняла
-- разговор, а не то, что человек видел в карточке.
--
-- applied_at — чтобы карточка не сработала дважды: sandbox остаётся открытым
-- после нажатия, и «Создать» можно нажать ещё раз.
ALTER TABLE "sandbox_messages" ADD COLUMN IF NOT EXISTS "kind" text;
ALTER TABLE "sandbox_messages" ADD COLUMN IF NOT EXISTS "payload" text;
ALTER TABLE "sandbox_messages" ADD COLUMN IF NOT EXISTS "applied_at" timestamp with time zone;
