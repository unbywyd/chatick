-- Статус «Проверено» между «На проверке» и «Готово».
--
-- Команда жаловалась, что review путает: он означал сразу два состояния —
-- «сдал, жду проверки» и «проверено, жду закрытия». По доске не было видно,
-- чей сейчас ход.
--
-- BEFORE 'done', а не в конец: порядок значений в перечислении — это порядок
-- работы, и по нему сортируются колонки на доске. Добавленный в хвост
-- verified оказался бы ПОСЛЕ done, то есть правее «Готово».
--
-- IF NOT EXISTS: миграции здесь накатываются вручную через psql, и повторный
-- прогон не должен падать.
ALTER TYPE "task_status" ADD VALUE IF NOT EXISTS 'verified' BEFORE 'done';
