-- Состав команды приходит только из внешней системы (SPEC §8.42).
--
-- У компании со своей системой люди заводятся, переводятся и увольняются там.
-- Если тех же людей можно добавлять и удалять ещё и у нас, два списка
-- разъезжаются: уволенный остаётся в проекте и продолжает читать переписку,
-- потому что его убрали «не в той системе».
--
-- Флаг запрещает именно запись — состав по-прежнему виден всем, кому и раньше.
-- Рядом с projects_via_api_only и по той же причине.
ALTER TABLE "companies" ADD COLUMN IF NOT EXISTS "members_via_api_only" boolean DEFAULT false NOT NULL;
