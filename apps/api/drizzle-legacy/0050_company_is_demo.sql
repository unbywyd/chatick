-- Пометка демонстрационной компании.
--
-- Демо-данные и настоящие живут в одной базе, и отличить их «по названию» —
-- ненадёжно: компанию переименуют, и скрипт очистки её не найдёт, либо, что
-- хуже, найдёт чужую с похожим именем.
--
-- Явный признак делает удаление безопасным: сносим строго помеченное,
-- настоящие данные не пострадают даже при ошибке в запросе.
ALTER TABLE "companies" ADD COLUMN IF NOT EXISTS "is_demo" boolean NOT NULL DEFAULT false;

CREATE INDEX IF NOT EXISTS "companies_is_demo_idx" ON "companies" ("is_demo") WHERE "is_demo";
