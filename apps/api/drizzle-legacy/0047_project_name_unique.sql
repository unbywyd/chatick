-- Два проекта с одним именем в одной компании — это ошибка, а не выбор:
-- люди в компании общие, и «сделай в Редизайне» перестаёт что-либо значить.
-- Особенно для ИИ-моста, где проект выбирается по названию из разговора.
--
-- Без учёта регистра: «Редизайн» и «редизайн» различают только машину.
CREATE UNIQUE INDEX IF NOT EXISTS "projects_company_name_uniq"
  ON "projects" ("company_id", lower("name"));
